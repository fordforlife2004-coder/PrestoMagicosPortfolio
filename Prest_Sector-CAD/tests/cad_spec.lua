-- Tests for shared/cad.lua, the rules both sides use. Run from the resource folder:  lua tests/cad_spec.lua

dofile('config.lua')
dofile('shared/cad.lua')
local C = CAD
local T = dofile('tests/runner.lua')()
local test, eq, ok = T.test, T.eq, T.ok

test('player IDs are whole numbers from 1 to 65535', function()
    eq(C.toId(3), 3)
    eq(C.toId('12'), 12)
    eq(C.toId(2.5), nil, 'a fraction')
    eq(C.toId('2.5'), nil)
    eq(C.toId(0), nil)
    eq(C.toId(65536), nil)
    eq(C.toId(nil), nil)
    eq(C.toId({}), nil)
end)

test('whole numbers in a range', function()
    eq(C.toInt('7', 1, 10), 7)
    eq(C.toInt(11, 1, 10), nil)
    eq(C.toInt(0, 1, 10), nil)
    eq(C.toInt(1.5, 1, 10), nil)
    eq(C.toInt('x', 1, 10), nil)
end)

test('text from players is trimmed, cut and has no control characters', function()
    eq(C.text('  hello  ', 20), 'hello')
    eq(C.text(nil, 20), '')
    eq(C.text(42, 20), '')
    eq(C.text('a\tb\0c', 20), 'a b c', 'short text: control characters become spaces')
    eq(C.text('line one\r\nline two', 300), 'line one\nline two', 'long text keeps line breaks')
    eq(C.text('a\n\n\n\n\nb', 300), 'a\n\nb', 'and squeezes runs of blank lines')
    eq(C.text('abcdef', 3), 'abc')
    -- 'é' is two bytes: cutting in the middle of it drops the whole character.
    eq(C.text('caf\195\169', 4), 'caf')
    eq(C.text('caf\195\169', 5), 'caf\195\169')
end)

test('plates are filed as letters and digits only', function()
    eq(C.plateKey(' ab-12 cd '), 'AB12CD')
    eq(C.plateKey('46EEK572'), '46EEK572')
    eq(C.plateKey('123456789'), nil, 'nine characters')
    eq(C.plateKey('---'), nil)
    eq(C.plateKey(nil), nil)
end)

test('abilities for each role', function()
    local a = C.abilities(Config, { police = true })
    ok(a['people.view'] and a['records.edit'] and a['warrants.request'] and a['unit.signon'])
    eq(a['warrants.approve'], nil, 'police cannot approve warrants')
    eq(a['records.delete'], nil)
    eq(a['dispatch.manage'], true, 'units can manage calls by default')
    local fire = C.abilities(Config, { fire = true })
    eq(fire['people.view'], true, 'fire can look people up by default')
    eq(fire['records.view'], nil, 'but not reports and warrants')
    eq(fire['records.edit'], nil)
    local judge = C.abilities(Config, { judge = true })
    ok(judge['warrants.approve'] and judge['records.view'])
    eq(judge['unit.signon'], nil, 'judges do not go on duty')
    eq(judge['records.edit'], nil)
    local sup = C.abilities(Config, { supervisor = true })
    for _, name in ipairs(C.ABILITY_NAMES) do eq(sup[name], true, 'supervisor has ' .. name) end
    local civ = C.abilities(Config, {})
    for _, name in ipairs(C.ABILITY_NAMES) do eq(civ[name], nil, 'a civilian has no ' .. name) end
end)

test('config switches change what units and fire can do', function()
    local strict = { UnitsCanManageCalls = false, FireCanSearchPeople = false }
    eq(C.abilities(strict, { police = true })['dispatch.manage'], nil)
    eq(C.abilities(strict, { fire = true })['people.view'], nil)
    eq(C.abilities(strict, { dispatch = true })['dispatch.manage'], true, 'dispatchers always can')
end)

test('report types and departments follow the roles', function()
    eq(table.concat(C.reportTypesFor(Config, { fire = true }), ','), 'medical,fire')
    eq(#C.reportTypesFor(Config, { police = true }), 5)
    eq(#C.reportTypesFor(Config, { admin = true }), #Config.ReportTypes)
    eq(#C.reportTypesFor(Config, {}), 0)
    eq(table.concat(C.departmentsFor(Config, { fire = true }), ','), 'lsfd,ems')
    eq(table.concat(C.departmentsFor(Config, { dispatch = true }), ','), 'comms')
    eq(#C.departmentsFor(Config, { supervisor = true }), #Config.Departments)
    eq(#C.departmentsFor(Config, { judge = true }), 0)
end)

test('charges add up, counted and merged', function()
    local totals = C.chargeTotals(Config, { { code = '1-01', count = 2 }, { code = '5-01' }, { code = '1-01', count = 1 } })
    eq(#totals.items, 2, 'the same charge twice is one line')
    eq(totals.items[1].code, '1-01')
    eq(totals.items[1].count, 3)
    eq(totals.items[1].fine, 2250)
    eq(totals.items[1].jail, 30)
    eq(totals.fine, 2250 + 150)
    eq(totals.jail, 30)
    eq(C.chargeTotals(Config, {}).fine, 0, 'no charges is zero')
end)

test('bad charges are refused with a reason', function()
    local function why(list) return select(2, C.chargeTotals(Config, list)) end
    T.contains(why({ { code = '9-99' } }), 'no charge 9-99')
    T.contains(why({ { code = '1-01', count = 0 } }), '1 to 20')
    T.contains(why({ { code = '1-01', count = 21 } }), '1 to 20')
    T.contains(why({ { code = '1-01', count = 1.5 } }), '1 to 20')
    T.contains(why('1-01'), 'Pick the charges')
    local many = {}
    for i = 1, 31 do many[i] = { code = '1-01' } end
    T.contains(why(many), '30 at most')
end)

test('the tablet gets the lists from the config, copied', function()
    local pub = C.publicConfig(Config)
    eq(#pub.departments, #Config.Departments)
    eq(pub.penal[1].charges[1].code, Config.PenalCode[1].charges[1].code)
    eq(pub.warrantsNeedApproval, true)
    eq(pub.storage, nil, 'nothing about storage')
    pub.departments[1].label = 'changed'
    ok(Config.Departments[1].label ~= 'changed', 'changing the copy leaves the config alone')
end)

test('the shipped config has no problems', function()
    local problems = C.checkConfig(Config)
    eq(#problems, 0, table.concat(problems, '; '))
end)

test('config mistakes are found', function()
    local function problemsWith(change)
        dofile('config.lua')
        change(Config)
        local text = table.concat(C.checkConfig(Config), '\n')
        dofile('config.lua')
        return text
    end
    T.contains(problemsWith(function(c) c.Storage = 'sqlite' end), "Config.Storage must be 'kvp' or 'oxmysql'")
    T.contains(problemsWith(function(c) c.Statuses[2].key = 'available' end), 'Config.Statuses has available twice')
    T.contains(problemsWith(function(c) c.Departments[1].role = 'swat' end), "Department lspd needs role")
    T.contains(problemsWith(function(c) table.remove(c.Priorities, 3) end), 'needs priority 3')
    T.contains(problemsWith(function(c) c.CallCodes[3].service = 'navy' end), 'unknown service navy')
    T.contains(problemsWith(function(c) c.CallCodes[1].code = '999' end), "needs a '911' code")
    T.contains(problemsWith(function(c) c.ReportTypes[1].roles = {} end), 'Report type incident has no roles')
    T.contains(problemsWith(function(c) c.PenalCode[2].charges[1].code = '1-01' end), 'Penal code 1-01 is listed twice')
    T.contains(problemsWith(function(c) c.PenalCode[1].charges[1].class = 'crime' end), "Penal code 1-01 needs class")
    T.contains(problemsWith(function(c) c.Departments = {} end), 'Config.Departments is empty')
end)

T.finish()
