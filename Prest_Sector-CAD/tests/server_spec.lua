test('attaching moves a unit off its old call, and the first unit is primary', function()
    world()
    signOn(POLICE, 'A-1', 'lspd')
    signOn(POLICE2, 'A-2', 'lspd')
    signOn(DISPATCH, 'D-1', 'comms')
    local one = F.must(DISPATCH, 'call.create', { code = '10-50' })
    local two = F.must(DISPATCH, 'call.create', { code = '10-10' })
    F.must(POLICE, 'call.attach', { id = one.id })
    F.must(POLICE2, 'call.attach', { id = one.id })
    local now = F.must(DISPATCH, 'call.get', { id = one.id })
    eq(now.primary, POLICE)
    eq(now.status, 'active')
    eq(#now.units, 2)
    F.must(POLICE, 'call.attach', { id = two.id })
    local old = F.must(DISPATCH, 'call.get', { id = one.id })
    eq(#old.units, 1, 'moved off the first call')
    eq(old.primary, POLICE2, 'and the next unit is primary')
    contains(old.notes[#old.notes].text, 'A-1 left the call')
    eq(F.must(DISPATCH, 'call.get', { id = two.id }).primary, POLICE)
    eq(#F.must(POLICE, 'call.attach', { id = two.id }).units, 1, 'attaching twice changes nothing')
end)

