    local warned = false
    for _, line in ipairs(F.logs) do
        if line:find('oxmysql is not started', 1, true) then warned = true end
    end
    ok(warned, 'says why in the console')
    local rows, queries = {}, {}
    world()
    F.others.oxmysql = {
        query = function(_, sql, params, cb)
            queries[#queries + 1] = sql
            if sql:find('^INSERT') then rows[params[1] .. ':' .. params[2]] = { kind = params[1], id = params[2], data = params[3] }
            elseif sql:find('^SELECT') then
                local out = {}
                for _, r in pairs(rows) do out[#out + 1] = r end
                return cb(out)
            end
            cb({})
        end,
    }
    F.resources.oxmysql = 'started'
    F.restart(function(c) c.Storage = 'oxmysql' end)
    eq(Store.backend(), 'oxmysql')
    contains(queries[1], 'CREATE TABLE IF NOT EXISTS `prest_sector_cad`')
    local p = newPerson(POLICE)
    ok(rows['person:' .. p.id], 'saved to MySQL')
    F.restart(function(c) c.Storage = 'oxmysql' end)
    eq(Store.get('person', p.id).first, 'Marcus', 'and loaded back')
    eq(newPerson(POLICE).id, p.id + 1)
end)

