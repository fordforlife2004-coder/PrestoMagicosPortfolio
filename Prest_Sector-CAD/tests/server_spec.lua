-- Tests for the CAD's server scripts, run in a fake FiveM server. From the resource folder:
--   lua tests/server_spec.lua

local F = dofile('tests/fake_server.lua')
local T = F.runner()
local test, eq, ok, contains = T.test, T.eq, T.ok, T.contains

local POLICE, FIRE, DISPATCH, SUP, JUDGE, CIV, CIV2, POLICE2 = 1, 2, 3, 4, 5, 6, 7, 8

-- A fresh server with one player in each role.
local function world(configure)
    F.players, F.kvp, F.resources, F.others, F.logs = {}, {}, {}, {}, {}
    F.now, F.gameMs = 1793750400, 1000000
    F.addPlayer(POLICE, 'Sam Ortiz', { aces = { 'cad.police' }, coords = vector3(10.0, 20.0, 30.0) })
    F.addPlayer(FIRE, 'Morgan Lee', { aces = { 'cad.fire' } })
    F.addPlayer(DISPATCH, 'Casey Ward', { aces = { 'cad.dispatch' } })
    F.addPlayer(SUP, 'Sgt Hale', { aces = { 'cad.supervisor' } })
    F.addPlayer(JUDGE, 'Judge Whitfield', { aces = { 'cad.judge' } })
    F.addPlayer(CIV, 'Jordan Hayes', { coords = vector3(500.0, -600.0, 25.0) })
    F.addPlayer(CIV2, 'Riley Chen', {})
    F.addPlayer(POLICE2, 'Dana Brooks', { aces = { 'cad.police' } })
    F.load(configure)
end

local function signOn(src, callsign, department) return F.must(src, 'unit.signOn', { callsign = callsign, department = department }) end

local function person(fields)
    local p = { first = 'Marcus', last = 'Bell', dob = '1991-04-12', gender = 'Male' }
    for k, v in pairs(fields or {}) do p[k] = v end
    return p
end

local function newPerson(src, fields) return F.must(src or POLICE, 'person.save', { person = person(fields) }) end

local function has(list, value)
    for _, v in ipairs(list or {}) do
        if v == value then return true end
    end
    return false
end

-- ------------------------------------------------------------------ session and roles

test('the session tells the tablet who you are and what you can do', function()
    world()
    local s = F.must(POLICE, 'session')
