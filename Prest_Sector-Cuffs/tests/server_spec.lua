-- Runs server/main.lua against tests/fake_server.lua, to check who can cuff whom and when.
-- Run from the resource folder with any Lua 5.3+:  lua tests/server_spec.lua

local F = dofile('tests/fake_server.lua')
dofile('config.lua')
dofile('shared/cuffs.lua')
dofile('server/main.lua')
local C = Cuffs
local t = F.runner()

local OFFICER, PARTNER, SUSPECT, OTHER, CIVILIAN = 1, 2, 3, 4, 5
local police = { ['cuffs.use'] = true }
F.addPlayer(OFFICER, 'Officer', { aces = police })
F.addPlayer(PARTNER, 'Partner', { aces = police })
F.addPlayer(SUSPECT, 'Suspect')
F.addPlayer(OTHER, 'Other')
F.addPlayer(CIVILIAN, 'Civilian')

local function stateOf(id) return GlobalState[C.cuffsKey(id)] end
local function escortOf(id) return GlobalState[C.escortKey(id)] end
local function lastMessage(id) local m = F.last(id, 'Prest_Sector-Cuffs:notify') return m and m.args[1] end
local function later(seconds) F.flush(seconds or 5) end

-- Puts everyone on foot in a row, half a metre apart, and lets cooldowns pass.
local function lineUp()
    for id = 1, 5 do
        if F.players[id] then
            F.leaveVehicle(id)
            F.moveTo(id, id * 0.5, 0.0)
            F.ped(id).attachedTo = nil
        end
    end
    later()
end

-- Cuffs a player all the way: the animation plays, then the cuffs close.
local function cuff(officer, suspect, style)
    F.send(officer, 'Prest_Sector-Cuffs:cuff', suspect, style)
    later()
end

t.test('nobody can cuff without the police ACE', function()
    lineUp()
    F.send(CIVILIAN, 'Prest_Sector-Cuffs:cuff', OTHER)
    later()
    t.eq(lastMessage(CIVILIAN), "You aren't allowed to use handcuffs.")
    t.eq(stateOf(OTHER), nil)
end)

t.test('cuffing plays the arrest on both players, then the cuffs close and everyone sees them', function()
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    local officerAnim, suspectAnim = F.last(OFFICER, 'Prest_Sector-Cuffs:animate'), F.last(SUSPECT, 'Prest_Sector-Cuffs:animate')
    t.eq(table.concat(officerAnim.args, ' '), 'cuff officer 3 rear')
    t.eq(table.concat(suspectAnim.args, ' '), 'cuff suspect 1 rear')
    t.eq(stateOf(SUSPECT), nil, 'not until the animation ends')
    F.flush(Config.Animations.cuff.seconds - 0.5)
    t.eq(stateOf(SUSPECT), nil, 'still closing')
    F.flush(1)
    t.eq(stateOf(SUSPECT), 'rear', 'in GlobalState, which only the server can write')
    t.eq(lastMessage(OFFICER), 'Cuffed behind the back.')
    t.eq(lastMessage(SUSPECT), 'You have been handcuffed behind the back.')
    t.eq(F.exports.IsCuffed(SUSPECT), true)
    t.eq(F.exports.IsCuffed('3'), true, 'the export takes an ID as text too')
end)

t.test('a cuffed player is not cuffed twice, and nobody can cuff someone while cuffed', function()
    lineUp()
    F.send(PARTNER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    t.eq(lastMessage(PARTNER), 'They are already cuffed.')
    F.send(SUSPECT, 'Prest_Sector-Cuffs:cuff', OTHER)
    t.eq(lastMessage(SUSPECT), "You aren't allowed to use handcuffs.")
    F.players[SUSPECT].aces['cuffs.use'] = true
    F.send(SUSPECT, 'Prest_Sector-Cuffs:cuff', OTHER)
    t.eq(lastMessage(SUSPECT), "You can't do that with your own hands cuffed.")
    F.players[SUSPECT].aces['cuffs.use'] = nil
end)

t.test('uncuffing takes the cuffs off at the end of its animation', function()
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:uncuff', SUSPECT)
    t.eq(F.last(SUSPECT, 'Prest_Sector-Cuffs:animate').args[1], 'uncuff')
    F.flush(1)
    t.eq(stateOf(SUSPECT), 'rear', 'still on')
    later(Config.Animations.uncuff.seconds)
    t.eq(stateOf(SUSPECT), nil)
    t.eq(lastMessage(SUSPECT), 'Your cuffs are off.')
    F.send(OFFICER, 'Prest_Sector-Cuffs:uncuff', SUSPECT)
    t.eq(lastMessage(OFFICER), "They aren't cuffed.")
end)

t.test('front cuffs by name or short name, with their own quicker animation; unknown styles are refused', function()
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT, 'Front')
    t.eq(F.last(SUSPECT, 'Prest_Sector-Cuffs:animate').args[4], 'front')
    F.flush(Config.Styles.front.cuff.seconds)
    t.eq(stateOf(SUSPECT), 'front', 'closed after the front animation')
    t.eq(lastMessage(SUSPECT), 'You have been handcuffed in front.')
    cuff(PARTNER, OTHER, 'back')
    t.eq(stateOf(OTHER), 'rear')
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', CIVILIAN, 'chains')
    t.eq(lastMessage(OFFICER), 'Unknown cuff style. Try one of: front, rear')
    F.exports.Uncuff(SUSPECT)
    F.exports.Uncuff(OTHER)
    t.eq(stateOf(SUSPECT), nil, 'Uncuff export')
end)

t.test('with no style typed, facing the suspect cuffs in front and standing behind them cuffs behind', function()
    lineUp()
    F.turn(SUSPECT, 90.0) -- facing west, toward the officer
    cuff(OFFICER, SUSPECT)
    t.eq(stateOf(SUSPECT), 'front')
    F.turn(OTHER, 90.0) -- facing west, with the partner just east of them: behind their back
    F.moveTo(PARTNER, 2.6, 0.0)
    cuff(PARTNER, OTHER)
    t.eq(stateOf(OTHER), 'rear')
    F.send(OFFICER, 'Prest_Sector-Cuffs:uncuff', SUSPECT)
    t.eq(F.last(SUSPECT, 'Prest_Sector-Cuffs:animate').args[4], 'front', 'front cuffs come off the front way')
    F.flush(Config.Styles.front.uncuff.seconds)
    t.eq(stateOf(SUSPECT), nil)
    F.exports.Uncuff(OTHER)
    F.turn(SUSPECT, 0.0)
    F.turn(OTHER, 0.0)
end)

t.test('the suspect must be within reach, in the same world instance, and not yourself', function()
    lineUp()
    F.moveTo(SUSPECT, 30.0, 0.0)
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    t.eq(lastMessage(OFFICER), 'Get closer to them first.')
    F.moveTo(SUSPECT, 2.5, 0.0)
    F.players[SUSPECT].bucket = 7
    local before = #F.toClients
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    t.eq(#F.toClients, before + 1, 'one reply and no arrest')
    t.eq(lastMessage(OFFICER), 'Get closer to them first.', 'another instance')
    F.players[SUSPECT].bucket = 0
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', OFFICER)
    t.eq(lastMessage(OFFICER), 'Nobody is close enough.')
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', 99)
    t.eq(lastMessage(OFFICER), 'Nobody is close enough.', 'not online')
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', 'nonsense')
    t.eq(lastMessage(OFFICER), 'Nobody is close enough.')
end)

t.test('player IDs from the network must be whole numbers: 3.5 or a table is nobody', function()
    lineUp()
    for _, bad in ipairs({ 3.5, -3, {}, true }) do
        F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', bad)
        t.eq(lastMessage(OFFICER), 'Nobody is close enough.', tostring(bad))
    end
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', 3.0)
    t.eq(F.last(SUSPECT, 'Prest_Sector-Cuffs:animate').args[3], OFFICER, '3.0 is player 3')
    later()
    t.eq(stateOf(SUSPECT), 'rear')
    t.eq(GlobalState['prestSectorCuffs:3'], 'rear', 'stored under the whole number')
    F.exports.Uncuff(3.0)
    t.eq(stateOf(SUSPECT), nil)
end)

t.test('a suspect who gets away before the cuffs close stays free', function()
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    F.moveTo(SUSPECT, 20.0, 0.0)
    later()
    t.eq(stateOf(SUSPECT), nil)
    t.eq(lastMessage(OFFICER), 'They pulled away before the cuffs closed.')
end)

t.test('a suspect who gets into a vehicle before the cuffs close is not cuffed in it', function()
    lineUp()
    local car = F.addVehicle(vector3(1.5, 1.0, 30.0))
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    F.seat(SUSPECT, car, -1)
    later()
    t.eq(stateOf(SUSPECT), nil)
    t.eq(lastMessage(OFFICER), 'They got into a vehicle.')
end)

t.test('one arrest at a time per officer and per suspect, and nobody joins in on either side', function()
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    F.send(PARTNER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    t.eq(lastMessage(PARTNER), 'Hold on, the cuffs are still going on or coming off.')
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', OTHER)
    t.eq(lastMessage(OFFICER), 'Finish what you are doing first.')
    F.send(PARTNER, 'Prest_Sector-Cuffs:cuff', OFFICER)
    t.eq(lastMessage(PARTNER), 'They are busy.', 'the officer mid-arrest')
    F.players[SUSPECT].aces['cuffs.use'] = true
    F.send(SUSPECT, 'Prest_Sector-Cuffs:cuff', OTHER)
    t.eq(lastMessage(SUSPECT), "You can't do that while you're being cuffed.")
    F.players[SUSPECT].aces['cuffs.use'] = nil
    later()
    t.eq(stateOf(SUSPECT), 'rear')
    t.eq(stateOf(OFFICER), nil)
end)

t.test('the cooldown is counted in milliseconds', function()
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:escort', SUSPECT)
    F.send(OFFICER, 'Prest_Sector-Cuffs:escort')
    t.eq(lastMessage(OFFICER), 'You let go.', 'letting go is never held back')
    F.flush(1.5)
    F.send(OFFICER, 'Prest_Sector-Cuffs:escort', SUSPECT)
    t.eq(lastMessage(OFFICER), 'Slow down a little.', '1.5 s is not 2 s')
    F.flush(0.6)
    F.send(OFFICER, 'Prest_Sector-Cuffs:escort', SUSPECT)
    t.eq(escortOf(SUSPECT), OFFICER)
    F.send(OFFICER, 'Prest_Sector-Cuffs:escort')
    later()
    F.exports.Uncuff(SUSPECT)
end)

t.test('either player leaving during the animation cancels it cleanly', function()
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    F.drop(OFFICER)
    later()
    t.eq(stateOf(SUSPECT), nil)
    F.addPlayer(OFFICER, 'Officer', { aces = police })
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    F.drop(SUSPECT)
    later()
    F.join(SUSPECT, 'Suspect')
    lineUp()
    t.eq(stateOf(SUSPECT), nil, 'not cuffed yet when they left, so they come back free')
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', OTHER)
    t.eq(F.last(OFFICER).name, 'Prest_Sector-Cuffs:animate', 'the officer is free to cuff again')
    later()
    F.exports.Uncuff(OTHER)
end)

t.test("a cancelled arrest's timer never finishes a newer one early", function()
    lineUp()
    F.send(OFFICER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    F.flush(1)
    F.drop(SUSPECT) -- leaves mid-arrest and comes straight back with the same ID
    F.join(SUSPECT, 'Suspect', { coords = vector3(1.5, 0.0, 30.0) })
    F.send(PARTNER, 'Prest_Sector-Cuffs:cuff', SUSPECT)
    F.flush(Config.Animations.cuff.seconds - 0.5) -- the first arrest's timer goes off in here
    t.eq(stateOf(SUSPECT), nil, 'not closed by the old timer')
    F.flush(1)
    t.eq(stateOf(SUSPECT), 'rear')
    t.eq(lastMessage(PARTNER), 'Cuffed behind the back.')
    F.exports.Uncuff(SUSPECT)
end)

t.test('leaving while cuffed is no way out: back within the time, cuffed again', function()
    lineUp()
    cuff(OFFICER, SUSPECT, 'front')
    F.drop(SUSPECT)
    t.eq(stateOf(SUSPECT), nil, 'their keys are cleared, so the next player with this ID starts free')
    F.flush(60 * 5)
    F.join(SUSPECT, 'Suspect')
    t.eq(stateOf(SUSPECT), 'front')
    t.eq(F.exports.IsCuffed(SUSPECT), true)
    F.drop(SUSPECT)
    F.flush(60 * 11)
    F.join(SUSPECT, 'Suspect')
    t.eq(stateOf(SUSPECT), nil, 'after Config.KeepCuffsMinutes they come back free')
    cuff(OFFICER, SUSPECT)
    F.drop(SUSPECT)
    F.join(SUSPECT, 'Suspect', { license = 'license:someone-else' })
    t.eq(stateOf(SUSPECT), nil, 'someone else getting the same ID is not cuffed')
    F.drop(SUSPECT)
    F.join(SUSPECT, 'Suspect')
    t.eq(stateOf(SUSPECT), 'rear', 'the real suspect still is')
    F.exports.Uncuff(SUSPECT)
    Config.KeepCuffsMinutes = 0
    cuff(OFFICER, SUSPECT)
    F.drop(SUSPECT)
    F.join(SUSPECT, 'Suspect')
    t.eq(stateOf(SUSPECT), nil, 'switched off')
    Config.KeepCuffsMinutes = 10
end)

