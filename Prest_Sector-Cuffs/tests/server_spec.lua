t.test('put in: a free passenger seat of a vehicle next to the officer; it lets go of the arm', function()
    lineUp()
    local car = F.addVehicle(vector3(3.0, 2.0, 30.0))
    F.send(OFFICER, 'Prest_Sector-Cuffs:escort', SUSPECT)
    later()
    local before = #F.toClients
    F.send(OFFICER, 'Prest_Sector-Cuffs:seat', nil, car, -1)
    F.send(OFFICER, 'Prest_Sector-Cuffs:seat', nil, car, 1.5)
    t.eq(#F.toClients, before, 'never the driver seat, and seats are whole numbers')
    F.seat(OTHER, car, 1)
    F.send(OFFICER, 'Prest_Sector-Cuffs:seat', nil, car, 1)
    t.eq(lastMessage(OFFICER), 'That seat is taken.')
    F.leaveVehicle(OTHER)
    F.send(OFFICER, 'Prest_Sector-Cuffs:seat', nil, car, 2)
    local seat = F.last(SUSPECT, 'Prest_Sector-Cuffs:seat')
    t.eq(seat.args[1], car)
    t.eq(seat.args[2], 2)
    t.eq(escortOf(SUSPECT), nil)
    F.send(PARTNER, 'Prest_Sector-Cuffs:escort', SUSPECT)
    t.eq(lastMessage(PARTNER), 'Hold on, they are getting into a vehicle.')
    F.send(PARTNER, 'Prest_Sector-Cuffs:seat', SUSPECT, car, 1)
    t.eq(lastMessage(PARTNER), 'Hold on, they are getting into a vehicle.', 'no second /putin while the first one runs')
    F.seat(SUSPECT, car, 2) -- what the suspect's game does
    later(10)
    F.send(OFFICER, 'Prest_Sector-Cuffs:seat', SUSPECT, car, 1)
    t.eq(lastMessage(OFFICER), 'They are already in a vehicle.')
end)

t.test('put in needs the vehicle near the officer, in the same instance, and never a getaway driver', function()
    lineUp()
    cuff(PARTNER, OTHER)
    local far = F.addVehicle(vector3(40.0, 0.0, 30.0))
    F.send(PARTNER, 'Prest_Sector-Cuffs:seat', OTHER, far, 1)
    t.eq(lastMessage(PARTNER), 'Get closer to the vehicle.')
    local elsewhere = F.addVehicle(vector3(2.0, 1.0, 30.0), { bucket = 9 })
    F.send(PARTNER, 'Prest_Sector-Cuffs:seat', OTHER, elsewhere, 1)
    t.eq(lastMessage(PARTNER), 'No vehicle close enough.')
    F.send(PARTNER, 'Prest_Sector-Cuffs:seat', OTHER, OFFICER, 1)
    t.eq(lastMessage(PARTNER), 'No vehicle close enough.', 'a player ID is not a vehicle')
    local getaway = F.addVehicle(vector3(2.0, 1.0, 30.0))
    F.seat(CIVILIAN, getaway, -1)
    F.send(PARTNER, 'Prest_Sector-Cuffs:seat', OTHER, getaway, 1)
    t.eq(lastMessage(PARTNER), 'Someone else is driving that vehicle.')
    F.leaveVehicle(CIVILIAN)
    local cruiser = F.addVehicle(vector3(2.0, 1.0, 30.0))
    F.seat(OFFICER, cruiser, -1)
    F.send(PARTNER, 'Prest_Sector-Cuffs:seat', OTHER, cruiser, 1)
    t.eq(F.last(OTHER, 'Prest_Sector-Cuffs:seat').args[1], cruiser, 'a partner officer driving is fine')
    F.leaveVehicle(OFFICER)
    later(10)
    F.exports.Uncuff(OTHER)
end)

