    G.tick(400)
    t.eq(update().plates.front.plate, 'ABC123', 'the hit takes the screen')
    t.eq(update().plates.front.status, 'hit', 'as a hit')
end)

t.test('answers that do not match a request are ignored', function()
    G.load()
