-- The radar in an officer's game (client/main.lua): when it shows, what it reads, locks and alarms,
-- the plate reader and its hits, the remote, saved settings and the keys.

local G = dofile('tests/fake_game.lua')
local t = G.runner()

local function mph(n) return n / 2.2369363 end
local function update() return G.last('update') end

-- In a police car going north at 45 mph, with the radar's first reading done.
local function inCar(configure, opts)
    G.load(configure, opts)
    local car = G.patrol(mph(45), opts)
    G.tick(500)
    return car
end

t.test('it shows only in the front of a radar car, for someone allowed to use it', function()
    G.load()
    G.tick(500)
    t.eq(G.last('show'), nil, 'on foot: never shown')
    G.patrol(0)
    G.tick(500)
    t.eq(G.last('show').visible, true, 'driving a police car')
    G.leave()
    G.tick(500)
    t.eq(G.last('show').visible, false, 'hidden on getting out')
    G.patrol(0, { seat = 0 })
    G.tick(500)
    t.eq(G.last('show').visible, true, 'front passenger')
    G.load()
    G.patrol(0, { seat = 1 })
    G.tick(500)
    t.eq(G.last('show'), nil, 'back seat: no')
end)

t.test('ordinary cars have no radar unless their model is listed', function()
    G.load()
    G.patrol(0, { class = 1, model = 'hash:sultan' })
    G.tick(500)
    t.eq(G.last('show'), nil, 'a Sultan')
    G.load(function(c) c.Vehicles.models = { 'sultan' } end)
    G.patrol(0, { class = 1, model = 'hash:sultan' })
    G.tick(500)
    t.eq(G.last('show').visible, true, 'listed in Config.Vehicles.models')
end)

t.test('someone the server says no to never sees it', function()
    G.load(nil, { denied = true })
    G.patrol(0)
    G.tick(500)
    t.eq(G.last('show'), nil, 'not allowed')
    G.state.prestSectorRadar = true
    G.tick(500)
    t.eq(G.last('show').visible, true, 'shows once the server allows it')
end)

t.test('/radar hides and shows it', function()
    inCar()
    G.command('radar')
    G.tick(500)
    t.eq(G.last('show').visible, false, 'hidden')
    G.command('radar')
    G.tick(500)
    t.eq(G.last('show').visible, true, 'shown again')
end)

t.test('the front and rear antennas and the patrol speed', function()
    G.load()
    G.addCar('AHEAD1', 0.0, 60.0, mph(58))
    G.addCar('BEHIND', 0.5, -80.0, mph(49))
    G.addCar('PARKED', 0.0, 20.0, 0.0)
    G.patrol(mph(45))
    G.tick(500)
    local u = update()
    t.eq(u.patrol, 45, 'patrol speed')
    t.eq(u.front.target, 58, 'front target (the parked car is skipped)')
    t.eq(u.front.fast, nil, 'no faster car')
    t.eq(u.rear.target, 49, 'rear target')
    t.eq(u.units, 'mph', 'units')
    t.eq(u.limit, 75, 'fast limit')
end)

t.test('a faster car further on shows as fast, with one alarm per car', function()
    G.load()
    G.addCar('NEAR', 0.0, 40.0, mph(52))
    local speeder = G.addCar('FAST', 1.0, 120.0, mph(88))
    G.patrol(mph(45))
    G.tick(500)
    t.eq(update().front.fast, 88, 'fast reading')
    t.eq(update().front.over, true, 'over the limit')
    t.eq(G.beeps('fast'), 1, 'one alarm')
    G.tick(1000)
    t.eq(G.beeps('fast'), 1, 'not again for the same car')
    G.setSpeed(speeder, mph(60))
    G.tick(400)
    t.eq(update().front.over, false, 'slowed down')
    G.setSpeed(speeder, mph(90))
    G.tick(400)
    t.eq(G.beeps('fast'), 2, 'over again: a new alarm')
end)

t.test('the lock key freezes an antenna until pressed again', function()
    G.load()
    local ahead = G.addCar('AHEAD1', 0.0, 60.0, mph(58))
    G.patrol(mph(45))
    G.tick(500)
    G.command('radarlockfront')
    G.setSpeed(ahead, mph(30))
    G.tick(400)
    t.eq(update().front.target, 58, 'locked on 58')
    t.eq(update().front.locked, true, 'lock lamp')
    t.eq(G.beeps('lock'), 1, 'a click')
    G.command('radarlockfront')
    G.tick(400)
    t.eq(update().front.target, 30, 'live again')
    t.eq(update().front.locked, false, 'lamp off')
end)

t.test('lock on fast locks by itself when a car goes over the limit', function()
    G.load()
    local speeder = G.addCar('FAST', 0.0, 50.0, mph(81))
    G.patrol(mph(45))
    G.callNui('settings', { fastLock = true })
    G.tick(500)
