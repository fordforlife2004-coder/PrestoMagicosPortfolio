end)

t.test('same and opposite modes, and antennas turned off', function()
    G.load()
    G.addCar('ONCOME', -3.0, 70.0, -mph(55))
    G.addCar('SAMEWY', 0.0, 100.0, mph(50))
    G.patrol(mph(45))
