t.test('the remote: needs a radar car, takes the mouse, closes with the car', function()
    G.load()
    G.tick(500)
    G.command('radarremote')
    t.contains(G.feed[#G.feed].text, 'Get in the front of a radar-equipped car', 'on foot')
    t.eq(G.focus, false, 'no mouse')
    G.patrol(0)
    G.tick(500)
    G.command('radarremote')
    t.eq(G.focus, true, 'mouse for the remote')
    t.eq(G.last('remote').open, true, 'open')
    t.ok(G.last('settings').settings.front, 'with the settings')
    G.callNui('close', {})
    t.eq(G.focus, false, 'closed')
    G.command('radarremote')
    G.leave()
    G.tick(500)
    t.eq(G.focus, false, 'getting out closes it')
    t.eq(G.last('remote').open, false, 'remote closed')
end)

t.test('settings from the remote are checked, saved, and back after a restart', function()
    inCar()
    local s = G.callNui('settings', { fastLimit = 999, volume = 30, rear = { on = false, mode = 'opp' }, pos = { x = 0.25, y = 0.5 } })
    t.eq(s.fastLimit, 250, 'limit capped')
    t.eq(s.rear.on, false, 'rear off')
    t.ok(G.kvp['prestSectorRadar:settings'], 'saved')
    G.load(nil, { keepKvp = true })
    G.patrol(0)
    G.tick(500)
    t.eq(update().limit, 250, 'the limit came back')
    t.eq(update().rear.on, false, 'rear still off')
    local moved = G.callNui('settings', { resetPos = true })
    t.eq(moved.pos, nil, 'put back in its corner')
    G.kvp['prestSectorRadar:settings'] = '{ broken'
    G.load(nil, { keepKvp = true })
    G.patrol(0)
    G.tick(500)
    t.eq(update().limit, Config.Radar.fastLimit, 'damaged settings fall back to the defaults')
end)

