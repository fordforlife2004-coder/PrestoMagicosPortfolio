t.test('two speeders in the beam: one alarm each, even when they swap places', function()
    G.load()
    local a = G.addCar('CARAAA', 0.0, 40.0, mph(80))
    G.patrol(mph(45))
    G.tick(500)
    t.eq(G.beeps('fast'), 1, 'the first speeder')
    local b = G.addCar('CARBBB', 0.0, 110.0, mph(95))
    G.tick(400)
    t.eq(G.beeps('fast'), 2, 'a faster one further on')
    for i = 1, 10 do
        G.setSpeed(a, mph(i % 2 == 0 and 90 or 91))
        G.setSpeed(b, mph(i % 2 == 0 and 91 or 90))
        G.tick(200)
    end
    t.eq(G.beeps('fast'), 2, 'swapping the lead sounds nothing new')
    G.move(b, 0.0, 400.0)
    G.tick(400)
    t.eq(G.beeps('fast'), 2, 'the second leaves: the first does not alarm again')
    G.setSpeed(a, mph(60))
    G.tick(400)
    G.setSpeed(a, mph(85))
    G.tick(400)
    t.eq(G.beeps('fast'), 3, 'the first slows down, then speeds up again: a new alarm')
    G.move(a, 30.0, 60.0)
    G.tick(400)
    G.move(a, 0.0, 60.0)
    G.tick(400)
    t.eq(G.beeps('fast'), 4, 'it leaves the beam (still nearby, still fast) and comes back: a new alarm')
end)

t.test('with lock on fast, unlocking or clearing does not lock the same speeder again at once', function()
    G.load()
    local speeder = G.addCar('FAST01', 0.0, 50.0, mph(85))
    G.patrol(mph(45))
    G.callNui('settings', { fastLock = true })
    G.tick(500)
    t.eq(update().front.locked, true, 'locked on the speeder')
    G.command('radarlockfront')
    G.tick(400)
    t.eq(update().front.locked, false, 'unlocked')
    G.command('radarlockfront')
    G.command('radarreset')
    G.tick(400)
    t.eq(update().front.locked, false, 'cleared, and the same speeder does not lock it again')
    G.move(speeder, 0.0, 400.0)
    G.addCar('FAST02', 0.0, 30.0, mph(90))
    G.tick(400)
    t.eq(update().front.locked, true, 'a new speeder locks it')
end)

