end)

t.test('the plate reader sends a new plate once, and shows the answer', function()
    G.load()
    G.addCar('abc 123', 0.0, 25.0, mph(50), { plateStyle = 3 })
    G.patrol(mph(45))
    G.tick(500)
    local checks = G.checks()
    t.eq(#checks, 1, 'one check')
    t.eq(checks[1].plate, 'ABC123', 'the tidied plate')
    t.eq(checks[1].camera, 'front', 'front camera')
    local p = update().plates.front
    t.eq(p.plate, 'ABC123', 'on screen')
    t.eq(p.style, 3, 'plate style')
    t.eq(p.status, 'reading', 'checking')
    G.answer(checks[1], { plate = 'ABC123', status = 'clear', reasons = {}, vehicle = 'Gray Sultan', owner = 'Ana Diaz' })
    G.tick(400)
    t.eq(update().plates.front.status, 'clear', 'clear')
    t.eq(update().plates.front.owner, 'Ana Diaz', 'owner')
    G.tick(5000)
    t.eq(#G.checks(), 1, 'not sent again while it stays in view')
    G.tick(Config.PlateReader.repeatSeconds * 1000)
    t.eq(#G.checks(), 2, 'sent again after Config.PlateReader.repeatSeconds')
end)

t.test('a hit: red, locked, an alarm, a notification, and Open in CAD', function()
    G.load()
    G.resources['Prest_Sector-CAD'] = 'started'
    G.addCar('ABC123', 0.0, 25.0, mph(50))
    G.patrol(mph(45))
    G.tick(500)
    G.answer(G.checks()[1], { plate = 'ABC123', status = 'hit', reasons = { 'BOLO: Robbery suspect' } })
    G.tick(400)
    local p = update().plates.front
    t.eq(p.status, 'hit', 'hit')
    t.eq(p.locked, true, 'locked on the hit')
    t.eq(p.reasons[1], 'BOLO: Robbery suspect', 'why')
    t.eq(G.beeps('hit'), 1, 'alarm')
    t.contains(G.feed[#G.feed].text, 'Plate reader hit: ABC123. BOLO: Robbery suspect', 'notification')
    t.eq(update().canOpenCad, true, 'Open in CAD is offered')
    G.command('radaropencad')
    t.eq(G.cadOpened[1], 'ABC123', 'opened on the CAD tablet')
end)

t.test('a hit still shows when the camera has moved on to another car', function()
    G.load()
    local first = G.addCar('ABC123', 0.0, 25.0, mph(50))
    G.patrol(mph(45))
